local M = {}

---@param style "dark"|"light"
---@return string
function M.slug(style)
  return style == "light" and "arrowlake_light" or "arrowlake"
end

---@param style "dark"|"light"
---@return string
function M.name(style)
  return style == "light" and "Arrowlake Light" or "Arrowlake"
end

---Generate an Omarchy colors.toml using the semantic palette. Omarchy derives
---the legacy color0..color15 ANSI names, shades, cursor and mode from these.
---@param colors ColorScheme
---@return string
function M.colors_toml(colors)
  local style = colors._style or "dark"

  ---@type [string, string][]
  local values = {
    { "mode", style },
    { "accent", colors.primary },
    { "selection", colors.backgrounds.visual },
    { "muted", colors.fg_gutter },

    { "background", colors.bg },
    { "dark_background", colors.bg_dark },
    { "darker_background", colors.bg_darker },
    { "lighter_background", colors.backgrounds.highlight },

    { "foreground", colors.fg },
    { "dark_foreground", colors.fg_darker },
    { "light_foreground", colors.fg_dark },
    { "bright_foreground", colors.fg_bright },

    { "red", colors.red },
    { "yellow", colors.yellow },
    { "orange", colors.orange },
    { "green", colors.green },
    { "cyan", colors.cyan },
    { "blue", colors.blue },
    { "magenta", colors.magenta },

    { "bright_red", colors.terminal.red_bright },
    { "bright_yellow", colors.terminal.yellow_bright },
    { "bright_green", colors.terminal.green_bright },
    { "bright_cyan", colors.terminal.cyan_bright },
    { "bright_blue", colors.terminal.blue_bright },
    { "bright_magenta", colors.terminal.magenta_bright },
  }

  local lines = { "# Generated by arrowlake.nvim. Do not edit." }
  for _, pair in ipairs(values) do
    if pair[1] ~= "mode" then
      assert(type(pair[2]) == "string" and pair[2]:match("^#%x%x%x%x%x%x$"), "invalid color for " .. pair[1])
    end
    lines[#lines + 1] = ("%s = \"%s\""):format(pair[1], pair[2])
  end

  return table.concat(lines, "\n") .. "\n"
end

---Generate the per-theme lazy.nvim spec Omarchy symlinks into
---~/.config/nvim/lua/plugins/theme.lua.
---
---The colorscheme travels as a global rather than inside a plugin entry, so a
---config that does not use LazyVim can read it without adding a distro
---dependency. `vim.g.arrowlake_colorscheme` is set when the spec is evaluated.
---@param style "dark"|"light"
---@return string
function M.neovim(style)
  return ([[
vim.g.arrowlake_colorscheme = "arrowlake-%s"

return {
  {
    "jadonwb/arrowlake.nvim",
    dev = true,
    priority = 1000,
  },
}
]]):format(style)
end

return M
